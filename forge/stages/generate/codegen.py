"""Generate: every run gets a NEW git repository holding the template plus everything rendered from the spec.

``generate(spec, out_root, run_id)`` creates ``<out_root>/<slug(app_name)>-<run_id>`` (refusing to touch an
existing path), copies the template, writes ``render(spec)``, produces the initial migration with
``prisma migrate diff`` inside the offline base image, and commits "G1: generated baseline" with forge's
tool identity. It returns the CodegenManifest: hashes of every immutable file, the editable globs and the
operations left to the builder.

``render_check(spec, repo)`` re-renders and lists the immutable generated files whose content differs (Verify's
regenerate-and-diff).
"""
from __future__ import annotations

import hashlib
import os
import re
import secrets
import shutil
import tempfile
from pathlib import Path

from forge.core import docker
from forge.core.config import TEMPLATE_DIR
from forge.core.gitrepo import commit_all, init_repo
from forge.models.appspec import AppSpecDraft
from forge.models.base import NameValue
from forge.models.run import CodegenManifest
from forge.stages.generate.manifest import EDITABLE_GLOBS, build_manifest, is_editable
from forge.stages.specify.render import MIGRATION_PATH, SCHEMA_PATH, render, stub_operations
from forge.stages.specify.render.naming import slug

COMMIT_MESSAGE = "G1: generated baseline"
RUN_ID = re.compile(r"^[A-Za-z0-9][A-Za-z0-9._-]{0,63}$")
SKIP_DIRS = frozenset({"node_modules", "dist", ".git", "__pycache__"})
SKIP_TOP = frozenset({"docker"})        # forge's own image recipes (base image), not part of a replica
SKIP_FILES = frozenset({".DS_Store"})
PRISMA = "/app/node_modules/.bin/prisma"

__all__ = ["CodegenError", "EDITABLE_GLOBS", "generate", "render_check", "repo_dir", "migration_sql",
           "template_files"]


class CodegenError(RuntimeError):
    pass


def repo_dir(spec: AppSpecDraft, out_root: Path, run_id: str) -> Path:
    if not RUN_ID.match(run_id):
        raise CodegenError(f"run id {run_id!r} must be letters, digits, '.', '_' or '-'")
    return Path(out_root) / f"{slug(spec.app_name)}-{run_id}"


def template_files() -> list[Path]:
    """Template files that belong in every replica (relative paths, sorted)."""
    out: list[Path] = []
    for dirpath, dirnames, filenames in os.walk(TEMPLATE_DIR, followlinks=False):
        rel_dir = Path(dirpath).relative_to(TEMPLATE_DIR)
        dirnames[:] = sorted(d for d in dirnames if d not in SKIP_DIRS and not (rel_dir == Path(".") and d in SKIP_TOP))
        for name in sorted(filenames):
            if name in SKIP_FILES:
                continue
            path = Path(dirpath) / name
            if path.is_symlink():
                raise CodegenError(f"template file {path} is a symlink")
            out.append(rel_dir / name)
    return sorted(out, key=lambda p: p.as_posix())


def _template_digest(files: list[Path]) -> str:
    h = hashlib.sha256()
    for rel in files:
        h.update(rel.as_posix().encode() + b"\0")
        h.update((TEMPLATE_DIR / rel).read_bytes() + b"\0")
    return h.hexdigest()


def _write(repo: Path, rel: str, content: str | bytes) -> None:
    target = repo / rel
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_bytes(content.encode("utf-8") if isinstance(content, str) else content)


def _migrate_diff(schema_dir: Path, run_id: str) -> str:
    """``prisma migrate diff --from-empty`` for ``schema_dir/schema.prisma``, offline in the base image."""
    image = docker.ensure_base_image()
    name = docker.project_name(run_id, f"migrate-diff-{secrets.token_hex(3)}")
    proc = docker.run(
        ["run", "--rm", "--name", name, "--network", "none", "--label", f"forge.run={run_id}",
         "-v", f"{schema_dir.resolve()}:/work:ro",
         "-e", "DATABASE_URL=postgresql://forge:forge@localhost:5432/forge",
         image, PRISMA, "migrate", "diff", "--from-empty", "--to-schema-datamodel", "/work/schema.prisma", "--script"],
        timeout=300, check=False)
    sql = proc.stdout
    if proc.returncode != 0 or "CREATE TABLE" not in sql:
        raise CodegenError(f"prisma migrate diff failed ({proc.returncode}): {(proc.stderr or sql).strip()[-2000:]}")
    return sql if sql.endswith("\n") else sql + "\n"


def migration_sql(schema: str, run_id: str = "codegen") -> str:
    """The initial migration for a schema text (runs in a throwaway directory)."""
    with tempfile.TemporaryDirectory(prefix="forge-schema-") as tmp:
        (Path(tmp) / "schema.prisma").write_text(schema)
        return _migrate_diff(Path(tmp), run_id)


def readme(spec: AppSpecDraft, run_id: str, stubs: list[str]) -> str:
    name = " ".join(spec.app_name.split()) or "Replica"
    lines = [
        f"# {name}",
        "",
        f"A full-stack replica generated by forge (run `{run_id}`) from `app-spec.json`: a React single-page app",
        "and a Fastify API on Postgres (Prisma), run with Docker Compose.",
        "",
        "## Run",
        "",
        "```sh",
        "docker compose up --build",
        "```",
        "",
        "Then open http://127.0.0.1:3000 (set `PORT` to publish on another port). Data lives in the `db-data`",
        "volume; `docker compose down -v` deletes it.",
        "",
        "## Layout",
        "",
        "| Path | Contents |",
        "|---|---|",
        "| `app-spec.json` | the spec everything generated is rendered from |",
        "| `contract/openapi.yaml` | the API contract (paths, fields, status codes) |",
        "| `db/schema.prisma`, `db/migrations/` | database schema and migrations |",
        "| `api/src/lib/` | server library: generic handlers, field rules, `db.write()` |",
        "| `api/src/generated/routes.ts` | one route per operation |",
        "| `api/src/stubs/` | actions implemented by hand |",
        "| `web/src/lib/` | UI library: screens, dialogs, forms, tables |",
        "| `web/src/generated/screens/` | one component per screen |",
        "| `web/src/styles/` | styles (Tailwind) |",
        "",
        "## Operational notes",
        "",
        "- `GET /__forge/health` reports readiness (including the database).",
        "- `FORGE_TEST_MODE=1` adds `GET /__forge/routes`, the list of registered API routes.",
        "- `FORGE_MUTANT=rollback-writes` rolls back every write while answering normally; forge uses it as a",
        "  negative control. Never set it outside tests.",
        "- `FORGE_BASE_IMAGE` selects the image the Dockerfile builds from (default `node:22-alpine`).",
    ]
    if stubs:
        lines += ["", "## Open work", "",
                  "These actions answer 501 until they are implemented in `api/src/stubs/`:", ""]
        lines += [f"- `{op}`" for op in stubs]
    return "\n".join(lines) + "\n"


def generate(spec: AppSpecDraft, out_root: Path, run_id: str) -> CodegenManifest:
    """Create the replica repository for this run and commit the G1 baseline."""
    files = render(spec)                       # fails on an invalid spec before anything touches the disk
    stubs = stub_operations(spec)
    repo = repo_dir(spec, out_root, run_id)
    Path(out_root).mkdir(parents=True, exist_ok=True)
    try:
        repo.mkdir()
    except FileExistsError:
        raise CodegenError(f"{repo} already exists; every run gets a new repository") from None
    try:
        template = template_files()
        for rel in template:
            _write(repo, rel.as_posix(), (TEMPLATE_DIR / rel).read_bytes())
        for rel, content in files.items():
            _write(repo, rel, content)
        _write(repo, MIGRATION_PATH, _migrate_diff((repo / SCHEMA_PATH).parent, run_id))
        _write(repo, "README.md", readme(spec, run_id, stubs))
        init_repo(repo)
        commit = commit_all(repo, COMMIT_MESSAGE)
    except BaseException:
        shutil.rmtree(repo, ignore_errors=True)
        raise
    inputs = [NameValue(name="appspec", value=hashlib.sha256(files["app-spec.json"].encode()).hexdigest()),
              NameValue(name="template", value=_template_digest(template))]
    return build_manifest(repo, commit, run_id, inputs=inputs, stubs=stubs)


def render_check(spec: AppSpecDraft, repo: Path, *, include_migration: bool = False) -> list[str]:
    """Generated files in ``repo`` that differ from a fresh render (editable files are skipped).

    With ``include_migration`` the initial migration is regenerated too (needs Docker).
    """
    repo = Path(repo)
    files = render(spec)
    if include_migration:
        files[MIGRATION_PATH] = migration_sql(files[SCHEMA_PATH])
    differs = []
    for rel, content in files.items():
        if is_editable(rel):
            continue
        target = repo / rel
        if target.is_symlink() or not target.is_file() or target.read_bytes() != content.encode("utf-8"):
            differs.append(rel)
    return sorted(differs)
