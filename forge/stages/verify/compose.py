"""The verify stack: a fresh clone at the candidate SHA, a pinned overlay that makes every network
internal, a compose lint, and the scenario runner executed from inside that network.

The overlay is generated by forge, never taken from the repo: it marks every network ``internal`` (no
route to the host or the internet), drops published ports (stacks run side by side and nothing is
exposed), builds images offline (``network: none``, FROM forge's template base image passed as the
``BASE_IMAGE`` build arg), turns on test mode for the app, gives it the network alias the runner browses,
and adds the ``runner`` service (forge's runner image, idle until ``docker compose exec``) with one bind
mount, the io directory.
"""
from __future__ import annotations

import json
import os
import re
import shutil
import threading
import time
import uuid
from pathlib import Path
from typing import Any
from collections.abc import Iterable

import yaml

from forge.core import docker
from forge.core.gitrepo import clone_at
from forge.models.run import APP_ALIAS, APP_URL_IN_NETWORK, MUTANT_ENV, TEST_MODE_ENV, RunnerRequest, RunnerResponse

OVERLAY = Path(".forge/verify.yaml")
MUTANT_OVERLAY = Path(".forge/mutant.yaml")
COMPOSE_NAMES = ("compose.yaml", "compose.yml", "docker-compose.yaml", "docker-compose.yml")
RUNNER = "runner"
IO_MOUNT = "/io"
# The runner browses the app by its network alias: "app" is an HSTS-preloaded TLD, so Chromium would
# silently upgrade http://app:3000 to https and every page load would fail.
APP_URL = APP_URL_IN_NETWORK
MUTANT_MODE = "rollback-writes"

_DANGEROUS_CAPS = {"ALL", "SYS_ADMIN", "NET_ADMIN", "SYS_PTRACE", "SYS_MODULE", "SYS_RAWIO", "DAC_READ_SEARCH",
                   "NET_RAW", "BPF", "PERFMON"}
_LOOPBACK = {"127.0.0.1", "localhost", "::1", "[::1]"}


class VerifyError(RuntimeError):
    pass


# ---------------------------------------------------------------------------------------------------
# Clone and overlay
# ---------------------------------------------------------------------------------------------------
def find_compose_file(repo: Path) -> Path:
    for name in COMPOSE_NAMES:
        if (repo / name).is_file():
            return repo / name
    raise VerifyError(f"no compose file in {repo}")


def prepare(repo: Path, sha: str, workdir: Path, *, runner_image: str | None = None,
            base_image: str | None = None, offline_build: bool = True) -> Path:
    """Clone ``repo`` at ``sha`` into ``workdir/repo`` and write the pinned ``.forge/verify.yaml`` overlay.

    Returns the clone. The runner's io directory is ``workdir/io`` (outside the clone, so the clone stays
    exactly the commit plus the overlay). With ``offline_build`` images build with no network, FROM
    ``base_image`` (default: forge's template base image, built on first use).
    """
    workdir = Path(os.path.realpath(workdir))
    workdir.mkdir(parents=True, exist_ok=True)
    clone = workdir / "repo"
    if clone.exists():
        shutil.rmtree(clone)
    clone_at(Path(repo), clone, sha)
    io = workdir / "io"
    io.mkdir(exist_ok=True)
    io.chmod(0o777)  # the runner writes results as root
    base = (base_image or docker.ensure_base_image()) if offline_build else None
    write_overlay(clone, io, runner_image or docker.ensure_runner_image(), base_image=base)
    return clone


class _Reset(list):
    """Serialised as ``!reset []``: compose drops the base file's value instead of merging into it."""


class _Dumper(yaml.SafeDumper):
    pass


_Dumper.add_representer(_Reset, lambda d, data: d.represent_sequence("!reset", data, flow_style=True))


class _Loader(yaml.SafeLoader):
    """Safe loading that understands compose's ``!reset`` and ``!override`` merge tags."""


def _construct_tagged(loader: yaml.SafeLoader, node: yaml.Node) -> Any:
    if isinstance(node, yaml.SequenceNode):
        return loader.construct_sequence(node, deep=True)
    if isinstance(node, yaml.MappingNode):
        return loader.construct_mapping(node, deep=True)
    return loader.construct_scalar(node)


for _tag in ("!reset", "!override"):
    _Loader.add_constructor(_tag, _construct_tagged)


def _load(path: Path) -> dict[str, Any]:
    data = yaml.load(path.read_text(), Loader=_Loader) or {}  # noqa: S506 - a SafeLoader subclass
    if not isinstance(data, dict):
        raise VerifyError(f"{path.name} is not a mapping")
    return data


def _service_networks(svc: Any) -> list[str]:
    nets = svc.get("networks") if isinstance(svc, dict) else None
    if isinstance(nets, dict):
        return list(nets)
    if isinstance(nets, list):
        return [str(n) for n in nets]
    return ["default"]


def overlay_for(base: dict[str, Any], io_dir: Path, runner_image: str, *,
                base_image: str | None = None) -> dict[str, Any]:
    """The pinned overlay for ``base`` (a compose file as loaded).

    With ``base_image`` every built service builds offline from it (``BASE_IMAGE`` build arg, network
    none). The app gets the network alias the runner browses (``APP_ALIAS``)."""
    services = base.get("services") or {}
    networks = [n for n in (base.get("networks") or {})]
    uses_default = any(not isinstance(s, dict) or not s.get("networks") for s in services.values())
    if uses_default or not networks:
        networks.append("default")
    overlay_services: dict[str, Any] = {}
    for name, svc in services.items():
        entry: dict[str, Any] = {}
        if isinstance(svc, dict) and svc.get("ports"):
            entry["ports"] = _Reset()
        if base_image and isinstance(svc, dict) and svc.get("build") is not None:
            entry["build"] = {"network": "none", "args": {"BASE_IMAGE": base_image}}
        if name == "app":
            entry["environment"] = {TEST_MODE_ENV: "1"}
            entry["networks"] = {n: {"aliases": [APP_ALIAS]} for n in _service_networks(svc)}
        if entry:
            overlay_services[name] = entry
    overlay_services[RUNNER] = {
        "image": runner_image,
        "pull_policy": "never",
        "entrypoint": ["sleep", "infinity"],
        "init": True,
        "shm_size": "512m",
        "networks": list(networks),
        "volumes": [{"type": "bind", "source": str(io_dir), "target": IO_MOUNT}],
    }
    return {"networks": {n: {"internal": True} for n in networks}, "services": overlay_services}


def write_overlay(clone: Path, io_dir: Path, runner_image: str, *, base_image: str | None = None) -> Path:
    base = _load(find_compose_file(clone))
    path = clone / OVERLAY
    path.parent.mkdir(parents=True, exist_ok=True)
    header = "# Written by forge verify; pinned, not part of the replica. Every network is internal.\n"
    overlay = overlay_for(base, Path(os.path.realpath(io_dir)), runner_image, base_image=base_image)
    path.write_text(header + yaml.dump(overlay, Dumper=_Dumper, sort_keys=False))
    return path


def write_mutant_overlay(clone: Path) -> Path:
    path = clone / MUTANT_OVERLAY
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(yaml.safe_dump({"services": {"app": {"environment": {MUTANT_ENV: MUTANT_MODE}}}}))
    return path


def compose_files(clone: Path, *, mutant: bool = False) -> list[Path]:
    files = [find_compose_file(clone), clone / OVERLAY]
    return files + [clone / MUTANT_OVERLAY] if mutant else files


def io_dir_of(files: list[Path]) -> Path:
    """The host directory the runner sees as /io (read back from the overlay)."""
    for f in reversed(files):
        runner = ((_load(f).get("services") or {}).get(RUNNER) or {}) if f.is_file() else {}
        for vol in runner.get("volumes") or []:
            if isinstance(vol, dict) and vol.get("target") == IO_MOUNT:
                return Path(vol["source"])
    raise VerifyError("the compose files define no runner io directory")


# ---------------------------------------------------------------------------------------------------
# Lint
# ---------------------------------------------------------------------------------------------------
def _real(path: str | Path) -> str:
    return os.path.realpath(os.path.expanduser(str(path)))


def _is_bind_source(source: str) -> bool:
    return bool(source) and (source.startswith(("/", ".", "~", "$")) or "/" in source or "\\" in source)


def _check_port(service: str, port: Any) -> str | None:
    if isinstance(port, dict):
        published, host_ip = port.get("published"), str(port.get("host_ip") or "")
        if published in (None, "") and not host_ip:
            return f"{service}: port {port.get('target')} is published on a random host port on all interfaces"
        return None if host_ip in _LOOPBACK else f"{service}: port {published} is not bound to 127.0.0.1"
    text = str(port).split("/", 1)[0]
    if text.startswith("["):  # [::1]:3000:3000
        host_ip = text[: text.index("]") + 1]
        return None if host_ip in _LOOPBACK else f"{service}: port {port} is not bound to 127.0.0.1"
    parts = text.split(":")
    if len(parts) == 3 and parts[0] in _LOOPBACK:
        return None
    return f"{service}: port {port} is not bound to 127.0.0.1"


def lint_config(config: dict[str, Any], *, base_dir: Path | None = None, allowed_binds: Iterable[Path] = (),
                resolved: bool = False) -> list[str]:
    """Problems that would let the stack escape its sandbox (empty list = clean).

    Rejects privileged containers, host namespaces, dangerous capabilities, devices, unconfined
    security profiles, the Docker socket, every host bind mount except ``allowed_binds`` (the runner's
    io directory), host paths smuggled in through volume driver options, ``include``/``extends`` of other
    files, external or fixed-name networks and volumes, ``container_name`` (both break the per-run
    isolation of stacks) and ports that are not bound to 127.0.0.1. ``resolved`` marks the output of
    ``docker compose config``, where compose itself fills in network and volume names.
    """
    problems: list[str] = []
    allowed = {_real(p) for p in allowed_binds}
    if config.get("include"):
        problems.append("top-level include pulls in files that are not linted")
    for nname, net in (config.get("networks") or {}).items():
        net = net if isinstance(net, dict) else {}
        if net.get("external"):
            problems.append(f"network {nname}: external networks escape the internal overlay")
        elif net.get("name") and resolved is False:
            problems.append(f"network {nname}: a fixed name is shared across runs")
        if str(net.get("driver") or "") in ("host", "macvlan", "ipvlan"):
            problems.append(f"network {nname}: driver {net['driver']}")
    for vname, vol in (config.get("volumes") or {}).items():
        vol = vol if isinstance(vol, dict) else {}
        opts = vol.get("driver_opts") or {}
        if opts.get("device") or "bind" in str(opts.get("o", "")):
            problems.append(f"volume {vname}: driver options mount a host path")
        if vol.get("external"):
            problems.append(f"volume {vname}: external volumes are shared across runs")
        elif vol.get("name") and resolved is False:
            problems.append(f"volume {vname}: a fixed name is shared across runs")
    for section in ("secrets", "configs"):
        for sname, item in (config.get(section) or {}).items():
            src = str((item or {}).get("file") or "") if isinstance(item, dict) else ""
            if src and (src.startswith(("/", "~")) or ".." in Path(src).parts):
                inside = base_dir is not None and _real(src).startswith(_real(base_dir) + os.sep)
                if not inside:
                    problems.append(f"{section} {sname}: reads a host file outside the repo ({src})")
    for name, svc in (config.get("services") or {}).items():
        if not isinstance(svc, dict):
            problems.append(f"{name}: service is not a mapping")
            continue
        if svc.get("privileged"):
            problems.append(f"{name}: privileged")
        if svc.get("container_name"):
            problems.append(f"{name}: container_name is shared across runs")
        mode = str(svc.get("network_mode") or "")
        if mode == "host" or mode.startswith("container:"):
            problems.append(f"{name}: network_mode {mode}")
        for key in ("pid", "ipc", "uts", "userns_mode", "cgroup"):
            if str(svc.get(key) or "") == "host":
                problems.append(f"{name}: {key} host")
        caps = {str(c).upper().removeprefix("CAP_") for c in svc.get("cap_add") or []}
        if caps & _DANGEROUS_CAPS:
            problems.append(f"{name}: cap_add {', '.join(sorted(caps & _DANGEROUS_CAPS))}")
        if svc.get("devices") or svc.get("device_cgroup_rules"):
            problems.append(f"{name}: host devices")
        if any("unconfined" in str(o) or "label=disable" in str(o) or "label:disable" in str(o)
               for o in svc.get("security_opt") or []):
            problems.append(f"{name}: security_opt disables confinement")
        extends = svc.get("extends")
        if isinstance(extends, dict) and extends.get("file"):
            problems.append(f"{name}: extends another file ({extends['file']})")
        for vol in svc.get("volumes") or []:
            if isinstance(vol, dict):
                vtype, source = str(vol.get("type") or "volume"), str(vol.get("source") or "")
                is_bind = vtype == "bind" or vtype == "npipe"
            else:
                parts = str(vol).split(":")
                source = parts[0] if len(parts) > 1 else ""
                is_bind = _is_bind_source(source)
            if "docker.sock" in source or "docker_engine" in source:
                problems.append(f"{name}: mounts the Docker socket")
            elif is_bind:
                host_path = _real(Path(base_dir) / source) if base_dir and not os.path.isabs(source) else _real(source)
                if host_path not in allowed:
                    problems.append(f"{name}: bind-mounts a host path ({source})")
        for port in svc.get("ports") or []:
            problem = _check_port(name, port)
            if problem:
                problems.append(problem)
    return problems


_VAR = re.compile(r"\$\$|\$\{([A-Za-z_]\w*)(?:(:?[-?+=])([^}]*))?\}|\$([A-Za-z_]\w*)")


def interpolate(value: Any) -> Any:
    """Resolve compose variables the way an unset environment would: ``${X:-d}`` becomes ``d``."""
    if isinstance(value, str):
        def sub(match: re.Match) -> str:
            if match.group(0) == "$$":
                return "$"
            op, arg = match.group(2), match.group(3)
            return arg if op in ("-", ":-", "=", ":=") else ""
        return _VAR.sub(sub, value)
    if isinstance(value, list):
        return [interpolate(v) for v in value]
    if isinstance(value, dict):
        return {k: interpolate(v) for k, v in value.items()}
    return value


def lint(compose_file: Path, *, allowed_binds: Iterable[Path] = ()) -> list[str]:
    """Lint one compose file as written, with variables at their defaults (see :func:`lint_config`)."""
    try:
        config = _load(Path(compose_file))
    except (OSError, yaml.YAMLError, VerifyError) as err:
        return [f"{Path(compose_file).name}: cannot be parsed ({err})"]
    return lint_config(interpolate(config), base_dir=Path(compose_file).parent, allowed_binds=allowed_binds)


def resolved_config(project: str, files: list[Path]) -> dict[str, Any]:
    """The merged configuration compose will actually run (paths resolved, overlays applied)."""
    proc = docker.compose(project, files, ["config", "--format", "json"], timeout=120)
    return json.loads(proc.stdout)


# ---------------------------------------------------------------------------------------------------
# Stack lifecycle and the in-network runner
# ---------------------------------------------------------------------------------------------------
_UP_LOCK = threading.Lock()
_POOLS_EXHAUSTED = "address pools"


def up(project: str, files: list[Path], *, timeout: int = 1800, wait_for_networks_s: int = 600,
       retries: int = 1) -> None:
    """Build and start the stack.

    Stacks start one at a time. A failed start is torn down and retried ``retries`` times (Docker can
    fail for reasons outside the replica). When Docker has no free network address pool left (each
    stack needs one per network), the start waits for a sibling stack to be torn down, for at most
    ``wait_for_networks_s``.
    """
    deadline = time.monotonic() + wait_for_networks_s
    failures = 0
    while True:
        with _UP_LOCK:
            try:
                docker.compose(project, files, ["up", "-d", "--build", "--remove-orphans", "--quiet-pull"],
                               timeout=timeout)
                return
            except docker.DockerError as err:
                down(project, files)
                exhausted = _POOLS_EXHAUSTED in str(err)
                if exhausted and time.monotonic() > deadline:
                    raise docker.DockerError(
                        "Docker has no free network address pool for this stack; remove unused networks "
                        "(docker network prune) or widen default-address-pools in the daemon config") from err
                if not exhausted:
                    failures += 1
                    if failures > retries:
                        raise
        time.sleep(10 if exhausted else 3)


def down(project: str, files: list[Path]) -> None:
    docker.compose(project, files, ["down", "-v", "--remove-orphans", "--rmi", "local", "-t", "5"], timeout=300,
                   check=False)


def logs(project: str, files: list[Path], service: str = "app", tail: int = 60) -> str:
    proc = docker.compose(project, files, ["logs", "--no-color", "--tail", str(tail), service], timeout=60, check=False)
    return (proc.stdout + proc.stderr)[-4000:]


def runner_exec(project: str, files: list[Path], args: list[str], *, timeout: int = 900):
    """Run a command in the idle runner container (``docker compose exec -T runner ...``)."""
    proc = docker.compose(project, files, ["exec", "-T", RUNNER, *args], timeout=timeout, check=False)
    if proc.returncode != 0 and re.search(r"is not running|no such service|not running", proc.stderr, re.I):
        proc = docker.compose(project, files, ["run", "--rm", "--no-deps", "-T", "--entrypoint", args[0], RUNNER,
                                               *args[1:]], timeout=timeout, check=False)
    return proc


def run_in_network(project: str, files: list[Path], request: RunnerRequest, *, timeout: int = 1800) -> RunnerResponse:
    """Run scenarios with the runner inside the stack's network; request and result travel through /io."""
    io = io_dir_of(files)
    name = f"run-{uuid.uuid4().hex[:12]}"
    req_file, res_file = io / f"{name}.request.json", io / f"{name}.result.json"
    req_file.write_text(request.model_dump_json())
    try:
        proc = runner_exec(project, files, ["python3", "-m", "forge.stages.oracle.runner_cli", "--request",
                                            f"{IO_MOUNT}/{req_file.name}", "--result", f"{IO_MOUNT}/{res_file.name}"],
                           timeout=timeout)
        if not res_file.exists():
            output = (proc.stderr or proc.stdout)[-2000:]
            raise VerifyError(f"runner wrote no result (exit {proc.returncode}): {output}")
        return RunnerResponse.model_validate_json(res_file.read_text())
    finally:
        for f in (req_file, res_file):
            f.unlink(missing_ok=True)
