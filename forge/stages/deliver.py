"""Deliver: tag the verified commit in the generated repo and commit a README and the verification report."""
from __future__ import annotations

import json
from pathlib import Path

from forge.core import gitrepo
from forge.models.appspec import AppSpecDraft
from forge.models.run import RunConfig
from forge.models.verification import Verification


def free_port(start: int = 3100) -> int:
    import socket

    for port in range(start, start + 200):
        with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as sock:
            if sock.connect_ex(("127.0.0.1", port)) != 0:
                return port
    return start


def deliver(repo: Path, config: RunConfig, spec: AppSpecDraft, verification: Verification, *, quick: bool,
            extra: str = "") -> str:
    # Pick a free local port so the replica never collides with other apps on 3000; compose reads PORT from .env.
    env = repo / ".env"
    existing = env.read_text().splitlines() if env.exists() else []
    kept = next((l.split("=", 1)[1].strip() for l in existing if l.startswith("PORT=")), "")
    port = int(kept) if kept.isdigit() else free_port()     # a re-delivery keeps the port the user already uses
    lines = [l for l in existing if not l.startswith("PORT=")]
    env.write_text("\n".join(lines + [f"PORT={port}"]) + "\n")
    tag = "forge/verified" if verification.overall == "verified" else "forge/partial"
    gitrepo.tag(repo, tag, verification.commit)
    (repo / "verification.json").write_text(json.dumps(verification.model_dump(mode="json"), indent=2) + "\n")
    (repo / "README.md").write_text(_readme(config, spec, verification, quick, tag, port) + ("\n" + extra if extra else ""))
    return gitrepo.commit_all(repo, f"Delivery: verification report ({verification.overall})")


def _readme(config: RunConfig, spec: AppSpecDraft, v: Verification, quick: bool, tag: str, port: int) -> str:
    rows = "\n".join(f"| {w.scenario_id} | {w.feature} | {'held-out' if w.held_out else 'protected'} | {w.status} |"
                     for w in v.workflows)
    checks = "\n".join(f"- {c.name}: **{c.status}**" + (f" — {c.detail}" if c.detail else "") for c in v.checks)
    limits = "\n".join(f"- {x}" for x in (v.limitations + spec.unsupported)) or "- none recorded"
    return f"""# {spec.app_name} (forge replica)

Generated by forge from {config.url} on {config.created_at[:10]} (run `{config.run_id}`).
This is an independent implementation of the observed behaviour, not a copy of the original's code.

## Run it

```sh
docker compose up --build
```

Then open http://127.0.0.1:{port} (the port is set in `.env`; change `PORT` there if it is taken).
Data lives in the Postgres volume; `docker compose down -v` resets it.
Migrations are in `db/migrations/` and are applied by the `migrate` service before the app starts.

## Verification ({'quick run, reduced assurance' if quick else 'full run'})

Overall: **{v.overall}** at commit `{v.commit[:12]}` (tag `{tag}`). Verified with no route to the original
(the replica ran on an internal Docker network); the same scenarios first passed on the original app.

| Scenario | Feature | Kind | Status |
|---|---|---|---|
{rows}

{checks}

## Limitations

{limits}

## Layout

- `app-spec.json` — the spec everything here was generated from
- `api/` Fastify API (`api/src/generated/` is generated; `api/src/stubs/` holds hand-written actions)
- `web/` React + Vite + Tailwind UI (`web/src/generated/screens/` may be refined by the builder)
- `db/` Prisma schema and migrations, `contract/openapi.yaml` the API contract
"""
