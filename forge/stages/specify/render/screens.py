"""Web files: one screen component per spec screen, the route table and the browser's operation table.

Each screen composes library components with literal props taken from the spec's elements, in element
order, so roles and accessible names match the original exactly:

* an ``open_create`` button owns the ``container`` (dialog) whose parent it is;
* a ``container`` holds fields, an alert, submit and cancel buttons;
* a ``list`` holds one ``list_row`` whose children are the parts of every row;
* parameters for API paths and links come from the route, the screen's record or the row.
"""
from __future__ import annotations

import html
import re
from dataclasses import dataclass, field as dc_field

from forge.models.appspec import SpecElement, SpecField, SpecScreen
from forge.stages.specify.render import naming
from forge.stages.specify.render.emit import js, jsx
from forge.stages.specify.render.model import Entity, Operation, SpecIndex

HEADER = "// Generated by forge from app-spec.json. Do not edit: change the spec and regenerate."
SCREEN_HEADER = (
    "// Generated by forge from app-spec.json (screen {sid}). The builder may edit this file, but every\n"
    "// role and accessible name must stay as it is: the acceptance scenarios find elements by them."
)
EMPTY_STATE = re.compile(r"^\s*(no\b|nothing\b|none\b|empty\b|there (are|is) no\b|you (have|don't have) no\b)", re.I)


def screen_component(screen_id: str) -> str:
    return naming.pascal(screen_id) + "Screen"


def screen_path(screen_id: str) -> str:
    return f"web/src/generated/screens/{naming.pascal(screen_id)}.tsx"


def dom_id(element_id: str) -> str:
    return "forge-" + re.sub(r"[^A-Za-z0-9_-]", "-", element_id)


@dataclass
class Ctx:
    """What the elements of one screen can draw parameters from."""

    screen: SpecScreen
    route_params: dict[str, str | None]       # route param -> entity
    record: Entity | None
    record_op: Operation | None
    elements: list[SpecElement]
    children: dict[str | None, list[SpecElement]]
    rendered: set[str] = dc_field(default_factory=set)
    imports: set[str] = dc_field(default_factory=set)
    headings: int = 0
    title_field: str | None = None
    form_ids: dict[str, str] = dc_field(default_factory=dict)   # container element id -> DOM id


class ScreenBuilder:
    def __init__(self, ix: SpecIndex, warnings: list[str]):
        self.ix = ix
        self.warnings = warnings
        self._param_entities = ix.operation_param_entities()

    # ---------------------------------------------------------------- helpers
    def warn(self, text: str) -> None:
        if text not in self.warnings:
            self.warnings.append(text)

    def route_param_entities(self, screen: SpecScreen) -> dict[str, str | None]:
        names = naming.route_params(screen.route)
        out: dict[str, str | None] = {}
        for n in names:
            ent = self._param_entities.get(n)
            if ent is None and n == "id" and screen.entity:
                ent = screen.entity
            if ent is None:
                ent = next((e for e in self.ix.entities
                            if n in (f"{e}_id", f"{naming.camel(e)}Id", f"{e}Id")), None)
            if ent is None and len(names) == 1 and screen.entity:
                ent = screen.entity
            out[n] = ent
        return out

    def resolve(self, name: str, entity: str | None, ctx: Ctx, item: str | None = None,
                item_source: str = "item", use_record: bool = True) -> dict | None:
        """Where the value of parameter ``name`` (an id of ``entity``) comes from in this context."""
        if item:
            ie = self.ix.entities[item]
            if entity == item:
                return {"from": item_source, "field": ie.id_field}
            ref = ie.reference_to(entity, prefer=name) if entity else None
            if ref:
                return {"from": item_source, "field": ref.name}
            if entity is None and ie.field(name):
                return {"from": item_source, "field": name}
        if name in ctx.route_params:
            return {"from": "route", "name": name}
        if entity:
            for rp, rent in ctx.route_params.items():
                if rent == entity:
                    return {"from": "route", "name": rp}
        if use_record and ctx.record:
            rec = ctx.record
            if entity == rec.name:
                return {"from": "record", "field": rec.id_field}
            ref = rec.reference_to(entity, prefer=name) if entity else None
            if ref:
                return {"from": "record", "field": ref.name}
            if entity is None and rec.field(name):
                return {"from": "record", "field": name}
        return None

    def op_params(self, op: Operation, ctx: Ctx, where: str, item: str | None = None,
                  use_record: bool = True) -> dict:
        params: dict = {}
        for p in op.params:
            src = self.resolve(p.name, p.entity, ctx, item=item, use_record=use_record)
            if src is None:
                self.ix.problem(f"{where}: cannot tell where path parameter {p.name!r} of {op.id!r} comes from "
                                f"on screen {ctx.screen.id!r} (route {ctx.screen.route})")
                src = {"from": "route", "name": p.name}
            params[p.name] = src
        return params

    def route_target(self, target_id: str, ctx: Ctx, where: str, item: str | None = None,
                     item_source: str = "item") -> dict | None:
        target = self.ix.screens.get(target_id)
        if target is None:
            self.ix.problem(f"{where}: unknown target screen {target_id!r}")
            return None
        trpe = self.route_param_entities(target)
        params: dict = {}
        for n in naming.route_params(target.route):
            src = self.resolve(n, trpe.get(n), ctx, item=item, item_source=item_source)
            if src is None:
                self.ix.problem(f"{where}: cannot fill route parameter {n!r} of screen {target_id!r} "
                                f"from screen {ctx.screen.id!r}")
                src = {"from": "route", "name": n}
            params[n] = src
        return {"path": target.route, "params": params}

    def operation(self, op_id: str | None, where: str, kinds: tuple[str, ...] | None = None) -> Operation | None:
        if op_id is None:
            return None
        op = self.ix.operations.get(op_id)
        if op is None:
            self.ix.problem(f"{where}: unknown operation {op_id!r}")
            return None
        if kinds and op.spec.kind not in kinds:
            self.ix.problem(f"{where}: operation {op_id!r} is a {op.spec.kind}, expected {' or '.join(kinds)}")
            return None
        return op

    def entity_field(self, entity: Entity | None, name: str | None, where: str) -> SpecField | None:
        if entity is None or name is None:
            return None
        f = entity.field(name)
        if f is None:
            self.ix.problem(f"{where}: {name!r} is not a field of {entity.name!r}")
        return f

    # ---------------------------------------------------------------- screen
    def context(self, screen: SpecScreen) -> Ctx:
        elements = [e for e in self.ix.spec.elements if e.screen == screen.id]
        order = {e.id: i for i, e in enumerate(elements)}
        elements.sort(key=lambda e: (e.order, order[e.id]))
        ids = {e.id for e in elements}
        children: dict[str | None, list[SpecElement]] = {}
        for e in elements:
            parent = e.parent if e.parent in ids else None
            if e.parent is not None and e.parent not in ids:
                self.ix.problem(f"element {e.id!r}: parent {e.parent!r} is not an element of screen {screen.id!r}")
            children.setdefault(parent, []).append(e)
        rpe = self.route_param_entities(screen)
        for n, ent in rpe.items():
            if ent is None:
                self.warn(f"screen {screen.id!r}: cannot tell which entity route parameter {n!r} identifies")
        record, record_op = self.choose_record(screen, rpe)
        return Ctx(screen=screen, route_params=rpe, record=record, record_op=record_op,
                   elements=elements, children=children)

    def choose_record(self, screen: SpecScreen, rpe: dict[str, str | None]) -> tuple[Entity | None, Operation | None]:
        candidates: list[str] = []
        if screen.entity:
            candidates.append(screen.entity)
        for n in reversed(list(rpe)):
            ent = rpe[n]
            if ent and ent not in candidates:
                candidates.append(ent)
        for ent in candidates:
            if ent not in rpe.values():
                continue
            for op in self.ix.operations.values():
                if op.spec.kind == "get" and op.entity == ent and all(
                        p.name in rpe or p.entity in rpe.values() for p in op.params):
                    return self.ix.entities[ent], op
        return None, None

    def build(self, screen: SpecScreen) -> str:
        ctx = self.context(screen)
        nodes = self.render_children(ctx, None, indent=6)
        for e in ctx.elements:
            if e.id not in ctx.rendered:
                self.warn(f"element {e.id!r} ({e.purpose}) on screen {screen.id!r} is not reachable "
                          "and was not rendered")
        props: list[tuple[str, object]] = [("title", screen.title)]
        if ctx.title_field:
            props.append(("titleField", ctx.title_field))
        if ctx.record_op:
            props.append(("record", {"operation": ctx.record_op.id,
                                     "params": self.op_params(ctx.record_op, ctx, f"screen {screen.id!r}",
                                                              use_record=False)}))
        has_alert = any(e.purpose == "status_message" and e.role == "alert" for e in ctx.children.get(None, []))
        if has_alert:
            props.append(("errorOutlet", False))
        ctx.imports.add("Screen")
        body = jsx("Screen", props, 4, children=nodes)
        imports = ", ".join(sorted(ctx.imports))
        return "\n".join([
            SCREEN_HEADER.format(sid=js(screen.id)),
            f'import {{ {imports} }} from "../../lib";',
            "",
            f"export default function {screen_component(screen.id)}() {{",
            "  return (",
            body,
            "  );",
            "}",
            "",
        ])

    # ---------------------------------------------------------------- top level
    def render_children(self, ctx: Ctx, parent: str | None, indent: int) -> list[str]:
        out: list[str] = []
        siblings = ctx.children.get(parent, [])
        for i, el in enumerate(siblings):
            if el.id in ctx.rendered:
                continue
            node = self.render_top(ctx, el, siblings[i + 1:], indent)
            if node:
                out.append(node)
        return out

    def render_top(self, ctx: Ctx, el: SpecElement, following: list[SpecElement], indent: int) -> str | None:
        ctx.rendered.add(el.id)
        where = f"element {el.id!r}"
        p = el.purpose
        if p == "heading":
            return self.heading(ctx, el, indent, where)
        if p == "text":
            if el.field:
                if ctx.record is None:
                    self.warn(f"{where}: bound to {el.field!r} but screen {ctx.screen.id!r} has no record")
                    return None
                if self.entity_field(ctx.record, el.field, where) is None:
                    return None
                ctx.imports.add("DetailText")
                return jsx("DetailText", [("field", el.field)], indent)
            ctx.imports.add("Text")
            return jsx("Text", [("text", el.name)], indent)
        if p == "navigate":
            return self.navigate(ctx, el, indent, where)
        if p == "list":
            return self.list(ctx, el, following, indent, where)
        if p == "open_create":
            return self.open_create(ctx, el, indent, where)
        if p == "container":
            return self.container(ctx, el, indent, where)
        if p == "field":
            ctx.imports.add("StandaloneField")
            f = ctx.record.field(el.field) if ctx.record and el.field else None
            return jsx("StandaloneField", [("label", el.name), ("multiline", bool(f and f.type == "text"))], indent)
        if p in ("submit_create", "submit_update"):
            form = self.form_for_submit(ctx, el)
            if form:
                ctx.imports.add("SubmitButton")
                return jsx("SubmitButton", [("label", el.name), ("form", form)], indent)
            self.warn(f"{where}: submit button outside any form")
            ctx.imports.add("InertButton")
            return jsx("InertButton", [("label", el.name)], indent)
        if p == "cancel":
            ctx.imports.add("InertButton")
            return jsx("InertButton", [("label", el.name)], indent)
        if p == "delete":
            return self.delete_button(ctx, el, indent, where)
        if p == "action":
            op = self.operation(el.operation, where)
            if op is None:
                self.ix.problem(f"{where}: an action button needs an operation")
                return None
            ctx.imports.add("ActionButton")
            return jsx("ActionButton", [("label", el.name), ("operation", op.id),
                                        ("params", self.op_params(op, ctx, where)),
                                        ("hideWhenApplied", bool(op.spec.action_sets))], indent)
        if p == "status_message":
            if el.role == "alert":
                ctx.imports.add("AlertMessage")
                return jsx("AlertMessage", [], indent)
            ctx.imports.add("StatusMessage")
            return jsx("StatusMessage", [], indent)
        if p == "list_row":
            self.warn(f"{where}: a list_row must be inside a list")
            return None
        self.warn(f"{where}: unsupported purpose {p!r}")
        return None

    def heading(self, ctx: Ctx, el: SpecElement, indent: int, where: str) -> str | None:
        level = 1 if ctx.headings == 0 else 2
        ctx.headings += 1
        if el.field:
            if ctx.record is None:
                self.ix.problem(f"{where}: heading bound to {el.field!r} but screen {ctx.screen.id!r} loads no record")
                return None
            if self.entity_field(ctx.record, el.field, where) is None:
                return None
            if ctx.title_field is None:
                ctx.title_field = el.field
            ctx.imports.add("DetailHeading")
            return jsx("DetailHeading", [("field", el.field), ("level", level)], indent)
        ctx.imports.add("Heading")
        return jsx("Heading", [("text", el.name), ("level", level)], indent)

    def navigate(self, ctx: Ctx, el: SpecElement, indent: int, where: str) -> str | None:
        if not el.target_screen:
            self.warn(f"{where}: navigate element without target_screen is shown as text")
            ctx.imports.add("Text")
            return jsx("Text", [("text", el.name)], indent)
        to = self.route_target(el.target_screen, ctx, where)
        if to is None:
            return None
        if el.role == "button":
            ctx.imports.add("NavButton")
            return jsx("NavButton", [("label", el.name), ("to", to)], indent)
        if el.field and (ctx.record is None or self.entity_field(ctx.record, el.field, where) is None):
            return None
        ctx.imports.add("NavLink")
        return jsx("NavLink", [("label", el.name), ("field", el.field), ("to", to)], indent)

    def delete_button(self, ctx: Ctx, el: SpecElement, indent: int, where: str) -> str | None:
        op = self.operation(el.operation, where, ("delete",))
        if op is None:
            self.ix.problem(f"{where}: a delete button needs a delete operation")
            return None
        props = self.delete_props(ctx, el, op, where)
        ctx.imports.add("DeleteButton")
        return jsx("DeleteButton", props, indent)

    def delete_props(self, ctx: Ctx, el: SpecElement, op: Operation, where: str) -> list[tuple[str, object]]:
        navigate_to = None
        if el.target_screen:
            navigate_to = self.route_target(el.target_screen, ctx, where)
        elif ctx.record and op.entity == ctx.record.name:
            # Deleting the screen's own record: go to the parent screen (or the start page).
            parent = ctx.screen.parent
            if parent and parent in self.ix.screens:
                navigate_to = self.route_target(parent, ctx, where)
            else:
                navigate_to = {"path": "/", "params": {}}
        return [("label", el.name), ("operation", op.id), ("params", self.op_params(op, ctx, where)),
                ("navigateTo", navigate_to)]

    # ---------------------------------------------------------------- lists
    def empty_state(self, ctx: Ctx, list_el: SpecElement, following: list[SpecElement]) -> SpecElement | None:
        for child in ctx.children.get(list_el.id, []):
            if child.purpose == "text" and not child.field:
                return child
        # The first sibling after the list, when it reads like an empty state ("No issues yet.").
        nxt = following[0] if following else None
        if nxt and nxt.purpose == "text" and not nxt.field and EMPTY_STATE.match(nxt.name):
            return nxt
        return None

    def list(self, ctx: Ctx, el: SpecElement, following: list[SpecElement], indent: int, where: str) -> str | None:
        op = self.operation(el.operation, where, ("list",))
        if op is None:
            candidates = [o for o in self.ix.operations.values()
                          if o.spec.kind == "list" and o.entity == ctx.screen.entity]
            if el.operation is None and len(candidates) == 1:
                op = candidates[0]
            else:
                self.ix.problem(f"{where}: a list needs a list operation")
                return None
        row_entity = self.ix.entities[op.entity]
        kids = ctx.children.get(el.id, [])
        row = next((k for k in kids if k.purpose == "list_row"), None)
        empty = self.empty_state(ctx, el, following)
        if empty:
            ctx.rendered.add(empty.id)
        part_elements = ctx.children.get(row.id, []) if row else [
            k for k in kids if k.purpose != "list_row" and (empty is None or k.id != empty.id)]
        if row:
            ctx.rendered.add(row.id)
            for extra in kids:
                if extra.purpose == "list_row" and extra.id != row.id:
                    self.warn(f"element {extra.id!r}: only the first list_row of a list is used")
        parts = []
        for part_el in part_elements:
            ctx.rendered.add(part_el.id)
            part = self.row_part(ctx, part_el, row_entity, f"element {part_el.id!r}")
            if part:
                parts.append(part)
        props: list[tuple[str, object]] = [
            ("label", el.name), ("operation", op.id), ("params", self.op_params(op, ctx, where)),
            ("parts", parts), ("empty", empty.name if empty else None), ("rowKey", row_entity.id_field)]
        if el.role in ("table", "grid", "treegrid"):
            if el.role != "table":
                props.append(("role", el.role))
            ctx.imports.add("EntityTable")
            return jsx("EntityTable", props, indent)
        if el.role != "list":
            self.warn(f"{where}: list role {el.role!r} is rendered as a list")
        ctx.imports.add("EntityList")
        return jsx("EntityList", props, indent)

    def row_part(self, ctx: Ctx, el: SpecElement, row_entity: Entity, where: str) -> dict | None:
        p = el.purpose
        if p == "navigate":
            if el.field and self.entity_field(row_entity, el.field, where) is None:
                return None
            if not el.target_screen:
                self.warn(f"{where}: row link without target_screen is shown as text")
                return {"kind": "text", "field": el.field, "text": el.name,
                        "header": naming.field_label(el.field) if el.field else "", "badge": False}
            to = self.route_target(el.target_screen, ctx, where, item=row_entity.name)
            if to is None:
                return None
            return {"kind": "link", "field": el.field, "text": el.name,
                    "header": naming.field_label(el.field) if el.field else "", "to": to}
        if p in ("text", "heading"):
            f = self.entity_field(row_entity, el.field, where) if el.field else None
            if el.field and f is None:
                return None
            return {"kind": "text", "field": el.field, "text": el.name,
                    "header": naming.field_label(el.field) if el.field else "",
                    "badge": bool(f and f.type == "enum")}
        if p == "action":
            op = self.operation(el.operation, where)
            if op is None:
                self.ix.problem(f"{where}: a row action needs an operation")
                return None
            return {"kind": "action", "label": el.name, "operation": op.id,
                    "params": self.op_params(op, ctx, where, item=row_entity.name),
                    "hideWhenApplied": bool(op.spec.action_sets)}
        if p == "delete":
            op = self.operation(el.operation, where, ("delete",))
            if op is None:
                self.ix.problem(f"{where}: a row delete needs a delete operation")
                return None
            return {"kind": "delete", "label": el.name, "operation": op.id,
                    "params": self.op_params(op, ctx, where, item=row_entity.name)}
        self.warn(f"{where}: {p!r} elements inside list rows are not supported")
        return None

    # ---------------------------------------------------------------- forms
    def form_operation(self, ctx: Ctx, container: SpecElement | None, owner: SpecElement | None,
                       items: list[SpecElement], where: str) -> Operation | None:
        submit = next((k for k in items if k.purpose in ("submit_create", "submit_update") and k.operation), None)
        for candidate in (submit, container, owner):
            if candidate is not None and candidate.operation:
                return self.operation(candidate.operation, where, ("create", "update", "action"))
        self.ix.problem(f"{where}: cannot tell which operation this form submits")
        return None

    def field_input(self, ctx: Ctx, el: SpecElement, entity: Entity, where: str) -> dict | None:
        f = self.entity_field(entity, el.field, where)
        if f is None:
            if el.field is None:
                self.ix.problem(f"{where}: a form field needs a field name")
            return None
        role = el.role
        if role in ("checkbox", "switch"):
            control = "checkbox"
        elif role in ("combobox", "listbox", "radiogroup"):
            control = "select"
        elif role == "spinbutton":
            control = "number"
        elif role in ("textbox", "searchbox"):
            control = {"text": "textarea", "date": "date", "datetime": "datetime"}.get(f.type, "text")
        else:
            control = {"enum": "select", "boolean": "checkbox", "text": "textarea", "integer": "number",
                       "number": "number", "date": "date", "datetime": "datetime"}.get(f.type, "text")
        options: list[str] = list(f.enum_values) if f.type == "enum" else []
        options_from = None
        if control == "select" and f.type == "boolean":
            options = ["true", "false"]
        elif control == "select" and f.type == "reference":
            options_from = self.reference_options(ctx, f, where)
            if options_from is None:
                control = "text"
        elif control == "select" and f.type != "enum":
            self.warn(f"{where}: a select for a {f.type} field is shown as a text box")
            control = "text"
        return {"name": f.name, "label": el.name, "control": control, "type": f.type, "options": options,
                "optionsFrom": options_from, "required": f.required, "default": f.default}

    def reference_options(self, ctx: Ctx, f: SpecField, where: str) -> dict | None:
        target = self.ix.entities.get(f.references or "")
        if target is None:
            return None
        for op in self.ix.operations.values():
            if op.spec.kind != "list" or op.entity != target.name:
                continue
            params = {}
            for p in op.params:
                src = self.resolve(p.name, p.entity, ctx)
                if src is None:
                    break
                params[p.name] = src
            else:
                label = next((g.name for g in target.fields if g.type in ("string", "text") and g.generated == "none"),
                             target.id_field)
                return {"operation": op.id, "params": params, "valueField": target.id_field, "labelField": label}
        self.warn(f"{where}: no list operation provides options for {f.name!r}; shown as a text box")
        return None

    def notice_for(self, ctx: Ctx, form_el: SpecElement | None) -> str | None:
        """Text of a screen-level status element (e.g. "Saved") that reports this form's success."""
        statuses = [e for e in ctx.children.get(None, []) if e.purpose == "status_message" and e.role != "alert"]
        if not statuses:
            return None
        if form_el is not None:
            after = [e for e in statuses if e.order >= form_el.order]
            if after:
                return after[0].name
        return statuses[0].name

    def form_items(self, ctx: Ctx, items: list[SpecElement], entity: Entity, op: Operation,
                   title: str | None, where: str) -> list[dict]:
        out: list[dict] = []
        for el in items:
            ctx.rendered.add(el.id)
            w = f"element {el.id!r}"
            p = el.purpose
            if p == "field":
                fi = self.field_input(ctx, el, entity, w)
                if fi:
                    out.append({"kind": "field", "field": fi})
            elif p == "status_message":
                out.append({"kind": "alert"} if el.role == "alert" else {"kind": "status", "text": el.name})
            elif p in ("submit_create", "submit_update"):
                out.append({"kind": "submit", "label": el.name})
            elif p == "cancel":
                out.append({"kind": "cancel", "label": el.name})
            elif p == "heading":
                if el.name != title and not el.field:
                    out.append({"kind": "text", "text": el.name})
            elif p == "text":
                out.append({"kind": "text", "text": el.name})
            elif p == "delete":
                dop = self.operation(el.operation, w, ("delete",))
                if dop:
                    props = dict(self.delete_props(ctx, el, dop, w))
                    out.append({"kind": "delete", "label": el.name, "operation": dop.id,
                                "params": props["params"], "navigateTo": props["navigateTo"]})
            elif p == "action":
                aop = self.operation(el.operation, w)
                if aop:
                    out.append({"kind": "action", "label": el.name, "operation": aop.id,
                                "params": self.op_params(aop, ctx, w)})
            elif p == "navigate" and el.target_screen:
                to = self.route_target(el.target_screen, ctx, w)
                if to:
                    out.append({"kind": "link", "label": el.name, "to": to})
            else:
                self.warn(f"{w}: {p!r} elements inside forms are not supported")
        if not any(i["kind"] == "submit" for i in out):
            self.warn(f"{where}: form has no submit button")
        return out

    def submit_target(self, ctx: Ctx, items: list[SpecElement], op: Operation, where: str) -> dict | None:
        submit = next((k for k in items if k.purpose in ("submit_create", "submit_update") and k.target_screen), None)
        if submit is None:
            return None
        return self.route_target(submit.target_screen, ctx, where, item=op.entity, item_source="result")

    def open_create(self, ctx: Ctx, el: SpecElement, indent: int, where: str) -> str | None:
        kids = ctx.children.get(el.id, [])
        if el.target_screen and not kids:
            to = self.route_target(el.target_screen, ctx, where)
            if to is None:
                return None
            ctx.imports.add("NavButton")
            return jsx("NavButton", [("label", el.name), ("to", to), ("primary", True)], indent)
        container = next((k for k in kids if k.purpose == "container"), None)
        items = ctx.children.get(container.id, []) if container else [k for k in kids if k.purpose != "container"]
        if container:
            ctx.rendered.add(container.id)
            for extra in kids:
                if extra.id != container.id:
                    self.warn(f"element {extra.id!r}: children of an open_create button besides its dialog are ignored")
        op = self.form_operation(ctx, container, el, items, where)
        if op is None:
            return None
        entity = self.ix.entities[op.entity]
        title = container.name if container and container.name else el.name
        form_items = self.form_items(ctx, items, entity, op, title, where)
        props: list[tuple[str, object]] = [
            ("trigger", el.name), ("title", title), ("operation", op.id),
            ("params", self.op_params(op, ctx, where)), ("items", form_items)]
        target = self.submit_target(ctx, items, op, where)
        if target:
            props.append(("navigateTo", target))
        ctx.imports.add("CreateDialog")
        return jsx("CreateDialog", props, indent)

    def container(self, ctx: Ctx, el: SpecElement, indent: int, where: str) -> str | None:
        items = ctx.children.get(el.id, [])
        op = self.form_operation(ctx, el, None, items, where)
        if op is None:
            return None
        entity = self.ix.entities[op.entity]
        if el.role == "dialog":
            self.warn(f"{where}: a dialog that no button opens is rendered as an inline form")
        if op.spec.kind == "update" and (ctx.record is None or ctx.record.name != op.entity):
            self.ix.problem(f"{where}: an edit form for {op.entity!r} needs a screen that loads that {op.entity}")
        label = el.name if el.role in ("form", "dialog", "region", "group") and el.name else None
        form_items = self.form_items(ctx, items, entity, op, label, where)
        component = {"create": "CreateForm", "update": "EditForm"}.get(op.spec.kind, "ActionForm")
        props: list[tuple[str, object]] = [
            ("label", label), ("operation", op.id), ("params", self.op_params(op, ctx, where)), ("items", form_items)]
        has_status = any(i["kind"] == "status" for i in form_items)
        updates_here = any(o.spec.kind in ("update", "action") for o in self.forms_on(ctx))
        if not has_status and (op.spec.kind != "create" or not updates_here):
            notice = self.notice_for(ctx, el)
            if notice:
                props.append(("successNotice", notice))
        target = self.submit_target(ctx, items, op, where)
        if target:
            props.append(("navigateTo", target))
        if el.id in self.external_submits(ctx):
            ctx.form_ids[el.id] = dom_id(el.id)
            props.append(("id", ctx.form_ids[el.id]))
        ctx.imports.add(component)
        return jsx(component, props, indent)

    def forms_on(self, ctx: Ctx) -> list[Operation]:
        ops = []
        for e in ctx.children.get(None, []):
            if e.purpose == "container":
                items = ctx.children.get(e.id, [])
                submit = next((k for k in items
                               if k.purpose in ("submit_create", "submit_update") and k.operation), None)
                op_id = (submit.operation if submit else None) or e.operation
                if op_id in self.ix.operations:
                    ops.append(self.ix.operations[op_id])
        return ops

    def external_submits(self, ctx: Ctx) -> set[str]:
        """Containers that a top-level submit button points at."""
        out = set()
        for e in ctx.children.get(None, []):
            if e.purpose in ("submit_create", "submit_update"):
                form = self.container_for_submit(ctx, e)
                if form:
                    out.add(form.id)
        return out

    def container_for_submit(self, ctx: Ctx, submit: SpecElement) -> SpecElement | None:
        forms = [e for e in ctx.children.get(None, []) if e.purpose == "container"]
        same_op = [f for f in forms if submit.operation and (
            f.operation == submit.operation
            or any(k.operation == submit.operation for k in ctx.children.get(f.id, [])))]
        if same_op:
            return same_op[0]
        return forms[0] if len(forms) == 1 else None

    def form_for_submit(self, ctx: Ctx, submit: SpecElement) -> str | None:
        form = self.container_for_submit(ctx, submit)
        return dom_id(form.id) if form else None


def render_screens(ix: SpecIndex, warnings: list[str]) -> dict[str, str]:
    builder = ScreenBuilder(ix, warnings)
    return {screen_path(s.id): builder.build(s) for s in ix.screens.values()}


def home_path(ix: SpecIndex) -> str | None:
    routes = [s.route for s in ix.screens.values()]
    if "/" in routes:
        return "/"
    return next((r for r in routes if not naming.route_params(r)), None)


def render_web_routes(ix: SpecIndex) -> str:
    lines = [HEADER, 'import type { ScreenRoute } from "../lib";']
    for s in ix.screens.values():
        lines.append(f'import {screen_component(s.id)} from "./screens/{naming.pascal(s.id)}";')
    lines += [
        "",
        f"export const APP_NAME = {js(ix.spec.app_name)};",
        f"export const HOME_PATH: string | null = {js(home_path(ix))};",
        "",
        "export const SCREENS: ScreenRoute[] = [",
    ]
    for s in ix.screens.values():
        lines.append(f"  {{ id: {js(s.id)}, path: {js(s.route)}, Component: {screen_component(s.id)} }},")
    lines.append("];")
    return "\n".join(lines) + "\n"


def operation_wire(op: Operation) -> dict:
    s = op.spec
    return {
        "id": s.id, "kind": s.kind, "method": s.method, "path": s.path, "entity": s.entity,
        "pathParams": [p.name for p in op.params], "requestFields": list(s.request_fields),
        "response": s.response, "listKey": s.list_key, "successStatus": s.success_status,
        "actionSets": [{"field": a.name, "value": a.value} for a in s.action_sets],
    }


def render_web_contract(ix: SpecIndex) -> str:
    ops = {op.id: operation_wire(op) for op in ix.operations.values()}
    return "\n".join([
        HEADER,
        'import type { OperationWire } from "../lib";',
        "",
        f"export const OPERATIONS: Record<string, OperationWire> = {js(ops, col=58)};",
        "",
    ])


