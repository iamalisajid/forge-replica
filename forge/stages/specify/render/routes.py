"""api/src/generated/routes.ts (one registerOperation call per operation) and api/src/stubs/<id>.ts."""
from __future__ import annotations

from forge.stages.specify.render import naming
from forge.stages.specify.render.emit import js
from forge.stages.specify.render.model import Entity, Operation, SpecIndex

HEADER = "// Generated by forge from app-spec.json. Do not edit: change the spec and regenerate."


def entity_config(entity: Entity) -> dict:
    return {
        "name": entity.name,
        "label": entity.spec.label,
        "delegate": entity.delegate,
        "idField": entity.id_field,
        "idType": entity.spec.id_type,
        "orderBy": entity.order_by,
        "fields": [
            {
                "name": f.name,
                "label": naming.field_label(f.name),
                "type": f.type,
                "required": f.required,
                "unique": f.unique,
                "enumValues": list(f.enum_values),
                "references": f.references if f.type == "reference" else None,
                "default": f.default if f.generated == "none" else None,
                "generated": f.generated,
            }
            for f in entity.fields
        ],
    }


def operation_config(op: Operation, entity: Entity | None = None) -> dict:
    s = op.spec
    return {
        "id": s.id,
        "kind": s.kind,
        "method": s.method,
        "path": s.path,
        "entity": s.entity,
        "pathParams": [{"name": p.name, "entity": p.entity, "role": p.role, "field": p.field} for p in op.params],
        "requestFields": list(s.request_fields),
        "response": s.response,
        "listKey": s.list_key,
        "successStatus": s.success_status,
        "actionSets": [{"field": a.name, "value": a.value} for a in s.action_sets],
        "stub": op.stub,
        "htmlFallback": op.html_fallback,
        "search": _search_config(op, entity),
    }


def _search_config(op: Operation, entity: Entity | None) -> dict | None:
    s = op.spec
    if s.kind != "list" or not s.search_param:
        return None
    fields = [f.name for f in entity.fields if f.type in ("string", "text")] if entity is not None else []
    return {"param": s.search_param, "fields": fields}


def stub_path(op: Operation) -> str:
    return f"api/src/stubs/{op.id}.ts"


def render_api_routes(ix: SpecIndex) -> str:
    stubs = [op for op in ix.operations.values() if op.stub]
    lines = [
        HEADER,
        'import type { FastifyInstance } from "fastify";',
        'import { registerOperation, type EntityConfig } from "../lib/index.js";',
    ]
    lines += [f'import stub_{op.id} from "../stubs/{op.id}.js";' for op in stubs]
    entities = {name: entity_config(e) for name, e in ix.entities.items()}
    prefix = "export const ENTITIES: Record<string, EntityConfig> = "
    lines += ["", f"{prefix}{js(entities, col=len(prefix))};", ""]
    lines.append("export function registerRoutes(app: FastifyInstance): void {")
    for op in ix.operations.values():
        prefix = "  registerOperation(app, ENTITIES, "
        config = js(operation_config(op, ix.entities.get(op.entity)), col=len(prefix), base=2)
        stub = f", stub_{op.id}" if op.stub else ""
        lines.append(f"{prefix}{config}{stub});")
    lines.append("}")
    return "\n".join(lines) + "\n"


def render_stub(op: Operation) -> str:
    s = op.spec
    return "\n".join([
        f"// Action {s.id}: {s.method} {s.path}",
        "// Codegen could not express this action, so it answers 501 until it is implemented here.",
        "// Rules: perform every write through ctx.write(...) (FORGE_MUTANT=rollback-writes relies on it), answer",
        "// with ctx.ok(ctx.serialize(...)) in the wire shape, and reject with ctx.fail(status, message).",
        'import type { ActionContext, OperationResult } from "../lib/index.js";',
        "",
        "/** What the original does, as recorded in the spec. */",
        f"export const NOTE = {js(s.action_note or '')};",
        "",
        "export default async function action(ctx: ActionContext): Promise<OperationResult> {",
        "  return ctx.notImplemented();",
        "}",
        "",
    ])
