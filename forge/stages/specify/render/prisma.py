"""db/schema.prisma: one model per entity, field names = wire names, enums stored as strings."""
from __future__ import annotations

import json

from forge.models.appspec import SpecField
from forge.stages.specify.render import naming
from forge.stages.specify.render.model import PRISMA_SAFE_STRING, Entity, SpecIndex

HEADER = "// Generated by forge from app-spec.json. Do not edit: change the spec and regenerate."
# "native" only: the client is generated inside the image that runs it, and engines for other platforms
# could not be downloaded by offline builds.
GENERATOR = """generator client {
  provider      = "prisma-client-js"
  binaryTargets = ["native"]
}"""
DATASOURCE = """datasource db {
  provider = "postgresql"
  url      = env("DATABASE_URL")
}"""

SCALARS = {
    "string": "String", "text": "String", "enum": "String", "integer": "Int", "number": "Float",
    "boolean": "Boolean", "datetime": "DateTime", "date": "DateTime",
}


def _unique_name(base: str, taken: set[str]) -> str:
    name, n = base, 2
    while name in taken:
        name = f"{base}_{n}"
        n += 1
    taken.add(name)
    return name


def _relation_base(fk: str) -> str:
    if fk.endswith("_id") and len(fk) > 3:
        return fk[:-3]
    if fk.endswith("Id") and len(fk) > 2:
        return fk[:-2]
    return fk + "_ref"


def _default(f: SpecField) -> str | None:
    """A Prisma @default for literals that are safe to embed; the API applies every other default."""
    if f.default is None or (not f.required and f.default.strip().lower() == "null"):
        return None
    value = f.default
    if f.type in ("string", "text", "enum"):
        return f"@default({json.dumps(value)})" if PRISMA_SAFE_STRING.match(value) else None
    if f.type == "integer":
        return f"@default({int(value.strip())})"
    if f.type == "number":
        return f"@default({float(value.strip())!r})"
    if f.type == "boolean":
        return f"@default({'true' if value.strip().lower() in ('true', '1') else 'false'})"
    if f.type == "datetime" and value.strip().lower() == "now":
        return "@default(now())"
    return None


class _Relations:
    """Names for relation fields on both sides, allocated once so they never collide."""

    def __init__(self, ix: SpecIndex):
        self.forward: dict[tuple[str, str], str] = {}            # (entity, fk) -> relation field name
        self.back: dict[str, list[tuple[str, Entity, SpecField]]] = {e: [] for e in ix.entities}
        taken = {name: {f.name for f in e.fields} for name, e in ix.entities.items()}
        for entity in ix.entities.values():
            for f in entity.fields:
                if f.type == "reference" and f.references in ix.entities:
                    self.forward[(entity.name, f.name)] = _unique_name(_relation_base(f.name), taken[entity.name])
        for entity in ix.entities.values():
            refs = [f for f in entity.fields if f.type == "reference" and f.references in ix.entities]
            for f in refs:
                target = f.references
                many = sum(1 for g in refs if g.references == target) > 1 or target == entity.name
                base = naming.plural(naming.snake(entity.name)) + (f"_by_{f.name}" if many else "")
                self.back[target].append((_unique_name(base, taken[target]), entity, f))

    @staticmethod
    def relation_name(entity: Entity, f: SpecField) -> str:
        return json.dumps(f"{entity.model}_{f.name}")


def _model(ix: SpecIndex, entity: Entity, rel: _Relations) -> str:
    rows: list[tuple[str, str, str]] = []
    for f in entity.fields:
        attrs: list[str] = []
        if f.generated == "id":
            if entity.spec.id_type == "uuid":
                rows.append((f.name, "String", "@id @default(uuid())"))
            else:
                rows.append((f.name, "Int", "@id @default(autoincrement())"))
            continue
        if f.generated == "created_at":
            rows.append((f.name, "DateTime", "@default(now())" + (" @db.Date" if f.type == "date" else "")))
            continue
        if f.generated == "updated_at":
            rows.append((f.name, "DateTime", "@updatedAt" + (" @db.Date" if f.type == "date" else "")))
            continue
        if f.type == "reference":
            target = ix.entities[f.references]
            base_type = "String" if target.spec.id_type == "uuid" else "Int"
        else:
            base_type = SCALARS[f.type]
        if f.unique:
            attrs.append("@unique")
        default = _default(f)
        if default:
            attrs.append(default)
        if f.type == "date":
            attrs.append("@db.Date")
        rows.append((f.name, base_type + ("" if f.required else "?"), " ".join(attrs)))
        if f.type == "reference":
            target = ix.entities[f.references]
            name = rel.forward[(entity.name, f.name)]
            rows.append((name, target.model + ("" if f.required else "?"),
                         f"@relation({_Relations.relation_name(entity, f)}, fields: [{f.name}], "
                         f"references: [{target.id_field}], onDelete: Cascade)"))
    for name, source, f in rel.back[entity.name]:
        rows.append((name, f"{source.model}[]", f"@relation({_Relations.relation_name(source, f)})"))

    width_name = max(len(r[0]) for r in rows)
    width_type = max(len(r[1]) for r in rows)
    lines = [f"model {entity.model} {{"]
    for name, type_, attrs in rows:
        line = f"  {name.ljust(width_name)} {type_.ljust(width_type)} {attrs}".rstrip()
        lines.append(line)
    lines.append("")
    for f in entity.fields:
        if f.type == "reference" and not f.unique and f.references in ix.entities:
            lines.append(f"  @@index([{f.name}])")
    lines.append(f"  @@map({json.dumps(entity.table)})")
    lines.append("}")
    return "\n".join(lines)


def render_prisma(ix: SpecIndex) -> str:
    rel = _Relations(ix)
    parts = [HEADER, GENERATOR, DATASOURCE]
    parts += [_model(ix, entity, rel) for entity in ix.entities.values()]
    return "\n\n".join(parts) + "\n"


